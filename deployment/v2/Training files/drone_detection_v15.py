def _list_audio_files(root: Path, exts=None) -> List[Path]:
    exts = exts or AudioWebScraper.AUDIO_EXTS
    if root is None or not Path(root).exists():
        return []
    files = []
    for ext in exts:
        files.extend(Path(root).rglob(f"*{ext}"))
    return sorted([p for p in files if p.is_file()])


def _copy_audio_file(src: Path, dst: Path, sr: int, force: bool = False) -> bool:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() and not force:
        return False
    y = load_audio_any(src, sr)
    y = np.asarray(y, dtype=np.float32)
    if len(y) == 0:
        return False
    sf.write(str(dst), normalize_peak(y), sr)
    return True


def _copy_grouped_files(files: List[Path], split_to_dir: Dict[str, Path], sr: int, force: bool = False,
                        test_fraction: float = 0.10, val_fraction: float = 0.15, seed: int = 42,
                        prefix: str = "custom") -> Dict[str, int]:
    stats = {"train": 0, "val": 0, "test": 0, "failed": 0, "skipped": 0}
    if not files:
        return stats
    groups = grouped_split_paths(files, seed=seed)
    # regroup with caller fractions when explicit test fraction requested
    if test_fraction > 0:
        rng = random.Random(seed)
        gid_to_files = defaultdict(list)
        for f in files:
            gid_to_files[infer_group_id(f)].append(f)
        grouped = list(gid_to_files.items())
        rng.shuffle(grouped)
        n = len(grouped)
        n_test = max(1, int(round(n * test_fraction))) if n >= 3 else 0
        n_val = max(1, int(round(n * val_fraction))) if n >= 4 else min(1, max(0, n - n_test - 1))
        n_train = max(0, n - n_val - n_test)
        custom = {"train": [], "val": [], "test": []}
        for i, (_, flist) in enumerate(grouped):
            if i < n_train:
                custom["train"].extend(flist)
            elif i < n_train + n_val:
                custom["val"].extend(flist)
            else:
                custom["test"].extend(flist)
        groups = custom
    for split, flist in groups.items():
        out_dir = split_to_dir[split]
        out_dir.mkdir(parents=True, exist_ok=True)
        for src in flist:
            stem = safe_slug(src.stem)
            dst = out_dir / f"{prefix}_{stem}.wav"
            try:
                changed = _copy_audio_file(src, dst, sr=sr, force=force)
                stats[split if changed else "skipped"] += 1 if changed else 1
            except Exception:
                stats["failed"] += 1
    return stats


