        with RemoteZip(url, **RZ_KWARGS) as rz: all_names = rz.namelist()
        norm_names = [n.replace("\\","/") for n in all_names]
        session_map = {}
        for path in norm_names:
            p = Path(path)
            if len(p.parts) < 2: continue
