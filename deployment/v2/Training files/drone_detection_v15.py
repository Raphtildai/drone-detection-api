    def _download_partial(self, url: str, proc: Path, n_sessions: int):
        from remotezip import RemoteZip
        RZ_KWARGS = {"initial_buffer_size": 64*1024*1024}
        AUDIO_CANDIDATES = {"output.wav","audio.wav"}
