def moving_average(x,k):
    if k<=1 or len(x)<2: return x.astype(np.float32)
    k=max(1,int(k)); pad=k//2
    xp=np.pad(x,(pad,pad),mode="edge"); w=np.ones(k)/k
    return np.convolve(xp,w,mode="valid")[:len(x)].astype(np.float32)

